func TestGenerateDynamicProtectedRouteWithTemplateException(t *testing.T) {
	out := GenerateDynamic(RouteGroup{
		AppUUID: "app-1",
		Routes: []Route{{
			FQDN: "app.example.com", Path: "/", TargetPort: 8080,
			PublicRoutes: []accessroute.Route{{
				Path: "/webhook/:provider/handler", Match: accessroute.MatchTemplate,
				Methods:    []string{"POST"},
				Parameters: map[string][]string{"provider": {"github", "stripe"}},
			}},
		}},
		Access: &AccessPolicy{
			Mode: "basic_auth", BasicAuthHash: "akerdock:$2y$10$hash",
		},
	}, 4)

	for _, want := range []string{
		"middlewares: [app-1-access]",
		"app-1-r0-public-0:",
		"PathRegexp(`^/webhook/(github|stripe)/handler$`)",
		"Method(`POST`)",
		"basicAuth:",
		"middlewares: [app-1-https-redirect]",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("protected routing missing %q\n%s", want, out)
		}
	}
	publicBlock := between(out, "    app-1-r0-public-0:\n", "  middlewares:\n")
	if strings.Contains(publicBlock, "app-1-access") {
		t.Fatalf("public router kept the access middleware:\n%s", publicBlock)
	}
	assertValidYAML(t, out)
}

func TestGenerateDynamicSSOCallbackIsUnprotected(t *testing.T) {
	out := GenerateDynamic(RouteGroup{
		AppUUID: "app-2",
		Routes:  []Route{{FQDN: "app.example.com", Path: "/", TargetPort: 80}},
		Access: &AccessPolicy{
			Mode:           "sso",
			ForwardAuthURL: "https://panel.example.com/webhooks/applications/forward-auth?resource=app-2",
			CallbackURL:    "https://panel.example.com",
		},
	}, 1)
	for _, want := range []string{
		"forwardAuth:",
		"?resource=app-2",
		"app-2-access-callback-0:",
		"Path(`/.akerdock/app-callback`)",
		"priority: 2000000",
		"passHostHeader: false",
		`url: "https://panel.example.com"`,
	} {
		if !strings.Contains(out, want) {
			t.Errorf("SSO routing missing %q\n%s", want, out)
		}
	}
	callbackBlock := between(out, "    app-2-access-callback-0:\n", "  middlewares:\n")
	if strings.Contains(callbackBlock, "middlewares:") {
		t.Fatalf("callback router must be unprotected:\n%s", callbackBlock)
	}
	assertValidYAML(t, out)
}

func TestGenerateWakerPublicRouteKeepsWakeMiddleware(t *testing.T) {
	out := GenerateWaker(RouteGroup{
		AppUUID: "sleeping",
		Routes: []Route{{
			FQDN: "sleep.example.com", Path: "/", TargetPort: 80,
			PublicRoutes: []accessroute.Route{{
				Path: "/hooks", Match: accessroute.MatchPrefix, Methods: []string{"POST"},
			}},
		}},
		Access: &AccessPolicy{Mode: "basic_auth", BasicAuthHash: "u:hash"},
	}, "resource-1", 1)
	if !strings.Contains(out, "middlewares: [sleeping-wake, sleeping-access]") {
		t.Fatalf("protected waker route did not compose wake + access:\n%s", out)
	}
	publicBlock := between(out, "    sleeping-r0-public-0:\n", "  middlewares:\n")
	if !strings.Contains(publicBlock, "middlewares: [sleeping-wake]") ||
		strings.Contains(publicBlock, "sleeping-access") {
		t.Fatalf("public waker route must wake without authenticating:\n%s", publicBlock)
	}
	assertValidYAML(t, out)
}

func TestPublicPriorityCannotShadowDescendantDomainRoute(t *testing.T) {
	if got, protected := publicPriority("/api"), Priority("/api"); got <= protected {
		t.Fatalf("public priority %d must beat its own protected router %d", got, protected)
	}
	if got, descendant := publicPriority("/api"), Priority("/api/admin"); got >= descendant {
		t.Fatalf("public priority %d must stay below descendant domain route %d", got, descendant)
	}
}

func between(value, start, end string) string {
	from := strings.Index(value, start)
	if from < 0 {
		return ""
	}
	value = value[from+len(start):]
	if to := strings.Index(value, end); to >= 0 {
		return value[:to]
	}
	return value
}

func assertValidYAML(t *testing.T, value string) {
	t.Helper()
	var document map[string]any
	if err := yaml.Unmarshal([]byte(value), &document); err != nil {
		t.Fatalf("generated routing is not valid YAML: %v\n%s", err, value)
	}
}

func TestGenerateWaker(t *testing.T) {
	// ADR-036: same hosts/priorities/TLS as the awake file, but services point
	// at the waker and each router stamps the wake header with the resource UUID.
	out := GenerateWaker(RouteGroup{
		AppUUID:    "9f3c2a1e",
		ForceHTTPS: true,
		Routes: []Route{
			{FQDN: "app.example.com", Path: "/", TargetPort: 3000},
		},
	}, "res-uuid-1234", 5)

	for _, want := range []string{
		"# generated by AkerDock — revision 5 — DO NOT EDIT",
		"9f3c2a1e-r0-web:",
		"9f3c2a1e-r0:",
		"rule: Host(`app.example.com`) && PathPrefix(`/`)",
		"service: 9f3c2a1e-waker",
		"9f3c2a1e-wake:",
		"X-AkerDock-Wake: \"res-uuid-1234\"",
		`url: "http://akerdock-agent:8080"`,
		"redirectScheme:",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("generated waker file missing %q\n%s", want, out)
		}
	}

	// The app's real container/port must NEVER appear: traffic goes to the waker.
	if strings.Contains(out, ":3000") {
		t.Errorf("waker file leaks the app target port\n%s", out)
	}
	// The websecure router must carry the wake middleware; the web router carries
	// the redirect (ForceHTTPS) instead, so the header is stamped post-redirect.
	if !strings.Contains(out, "middlewares: [9f3c2a1e-wake]") {
		t.Errorf("websecure router missing wake middleware\n%s", out)
	}
}

func TestGenerateWakerNoForceHTTPS(t *testing.T) {
	// Without ForceHTTPS the web router itself must carry the wake middleware,
	// otherwise a plain-HTTP first hit would never wake the target.
	out := GenerateWaker(RouteGroup{
		AppUUID: "abcd",
		Routes:  []Route{{FQDN: "x.example.com", Path: "/", TargetPort: 80}},
	}, "res-9", 1)
	if strings.Count(out, "middlewares: [abcd-wake]") != 2 {
		t.Errorf("both routers must carry the wake middleware when no redirect\n%s", out)
	}
}

func TestGenerateControlPlane(t *testing.T) {
	out := GenerateControlPlane("manager.example.com", 8080, 7)

	for _, want := range []string{
		"# generated by AkerDock — revision 7 — DO NOT EDIT",
		"00-control-plane-r0-web:",
		"00-control-plane-r0:",
		"rule: Host(`manager.example.com`) && PathPrefix(`/`)",
		"middlewares: [00-control-plane-https-redirect]",
		"certResolver: http01",
		`url: "http://host.docker.internal:8080"`,
		"redirectScheme:",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("control-plane file missing %q\n%s", want, out)
		}
	}
	// Idempotence matters: bootstrap compares this content with the last
	// applied revision to skip a no-op re-apply on every proxy start.
	if out != GenerateControlPlane("manager.example.com", 8080, 7) {
		t.Fatal("generation must be deterministic")
	}
}

func TestGenerateDynamicDeterministicOrder(t *testing.T) {
	rg := RouteGroup{AppUUID: "u", Routes: []Route{
		{FQDN: "b.example.com", Path: "/", TargetPort: 80},
		{FQDN: "a.example.com", Path: "/", TargetPort: 80},
	}}
	a := GenerateDynamic(rg, 1)
	rg.Routes[0], rg.Routes[1] = rg.Routes[1], rg.Routes[0]
	b := GenerateDynamic(rg, 1)
	if a != b {
		t.Fatal("generation must be deterministic regardless of declaration order")
	}
	if strings.Index(a, "a.example.com") > strings.Index(a, "b.example.com") {
		t.Fatal("routes must be sorted by (fqdn, path)")
	}
}
