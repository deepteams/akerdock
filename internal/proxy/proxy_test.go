func TestPriorityFormula(t *testing.T) {
	// §3.1: most specific path first, whatever the declaration order.
	cases := map[string]int{"/": 1, "/api": 1004, "/api/v2": 2007}
	for path, want := range cases {
		if got := Priority(path); got != want {
			t.Errorf("Priority(%q) = %d, want %d", path, got, want)
		}
	}
	if Priority("/api/v2") <= Priority("/api") || Priority("/api") <= Priority("/") {
		t.Fatal("specificity ordering broken")
	}
}

func TestGenerateDynamic(t *testing.T) {
	out := GenerateDynamic(RouteGroup{
		AppUUID:    "9f3c2a1e",
		ForceHTTPS: true,
		Routes: []Route{
			{FQDN: "app.example.com", Path: "/", TargetPort: 3000},
		},
	}, 41)

	for _, want := range []string{
		"# generated by AkerDock — revision 41 — DO NOT EDIT",
		"9f3c2a1e-r0-web:",
		"9f3c2a1e-r0:",
		"rule: Host(`app.example.com`) && PathPrefix(`/`)",
		"priority: 1",
		"middlewares: [9f3c2a1e-https-redirect]",
		"certResolver: http01",
		`url: "http://9f3c2a1e:3000"`,
		"redirectScheme:",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("generated file missing %q\n%s", want, out)
		}
	}
}

func TestGenerateControlPlane(t *testing.T) {
	out := GenerateControlPlane("manager.example.com", 8080, 7)

	for _, want := range []string{
		"# generated by AkerDock — revision 7 — DO NOT EDIT",
		"00-control-plane-r0-web:",
		"00-control-plane-r0:",
		"rule: Host(`manager.example.com`) && PathPrefix(`/`)",
		"middlewares: [00-control-plane-https-redirect]",
		"certResolver: http01",
		`url: "http://host.docker.internal:8080"`,
		"redirectScheme:",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("control-plane file missing %q\n%s", want, out)
		}
	}
	// Idempotence matters: bootstrap compares this content with the last
	// applied revision to skip a no-op re-apply on every proxy start.
	if out != GenerateControlPlane("manager.example.com", 8080, 7) {
		t.Fatal("generation must be deterministic")
	}
}

func TestGenerateDynamicDeterministicOrder(t *testing.T) {
	rg := RouteGroup{AppUUID: "u", Routes: []Route{
		{FQDN: "b.example.com", Path: "/", TargetPort: 80},
		{FQDN: "a.example.com", Path: "/", TargetPort: 80},
	}}
	a := GenerateDynamic(rg, 1)
	rg.Routes[0], rg.Routes[1] = rg.Routes[1], rg.Routes[0]
	b := GenerateDynamic(rg, 1)
	if a != b {
		t.Fatal("generation must be deterministic regardless of declaration order")
	}
	if strings.Index(a, "a.example.com") > strings.Index(a, "b.example.com") {
		t.Fatal("routes must be sorted by (fqdn, path)")
	}
}
